"""Writes results/RESULTS.md (all tables of the paper) from the raw result files.

    python analysis/make_report.py [--results results]

Standard library only. Every number is computed from items.csv, calls.csv, speed.csv,
gpu.csv and summary.json; nothing is typed by hand.
"""
from __future__ import annotations

import argparse
import random
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
sys.path.insert(0, str(HERE))

from stats import BOOT_SEED, N_BOOT, boot_mean, diff_of_means, paired_boot, ratio_of_means, wilson  # noqa: E402
from tokens_per_task.config import CONFIGS, MODEL_OF, SETTING_OF  # noqa: E402
from tokens_per_task.results_io import read_rows  # noqa: E402
from tokens_per_task.summary import read_speed, speed_from_calls, summarise_rows  # noqa: E402

TASKS = {"T1": "T1 Classify — Banking77, 100 customer messages, 77 intents",
         "T2": "T2 Calculate — GSM8K, 100 grade-school word problems",
         "T4": "T4 Hard maths — MATH-500 level 5, 50 problems with integer answers",
         "T3": "T3 Agent — 20 analyst questions on a synthetic invoice ledger, 3 tools, ≤ 15 steps"}
ORDER = list(CONFIGS)

# (label, condition A, condition B): effect of A relative to B on the same items
CONTRASTS = [
    ("Qwen3.5-4B: thinking on vs off", "S-on", "S"),
    ("Qwen3.8-27B: effort low vs thinking off", "Q-low", "Q-off"),
    ("Qwen3.8-27B: effort medium vs thinking off", "Q-med", "Q-off"),
    ("Qwen3.8-27B: effort xhigh vs thinking off", "Q-xhigh", "Q-off"),
    ("Gemma 4 31B: thinking on vs off", "G-on", "G-off"),
    ("gpt-oss-20b: effort high vs low", "O-high", "O-low"),
    ("Small model thinking vs large model direct (Qwen3.5-4B on vs Qwen3.8-27B off)", "S-on", "Q-off"),
]


def fmt(v, d=0):
    if v is None or v == "":
        return "–"
    return f"{v:,.{d}f}" if isinstance(v, (int, float)) else str(v)


def pct(v):
    return "–" if v is None else f"{100 * v:.0f}%"


def ci_pct(lo, hi):
    return f"[{100 * lo:.0f}, {100 * hi:.0f}]"


def ci_int(lo, hi):
    return f"[{lo:,.0f}, {hi:,.0f}]"


def per_item(items, config, task, field):
    return {r["item_id"]: float(r[field]) for r in items if r["config"] == config and r["task"] == task}


def unpaired_ratio_ci(xa, xb, n_boot=N_BOOT, seed=BOOT_SEED):
    rng = random.Random(seed)
    vals = []
    for _ in range(n_boot):
        a = [xa[rng.randrange(len(xa))] for _ in xa]
        b = [xb[rng.randrange(len(xb))] for _ in xb]
        vals.append(statistics.fmean(a) / statistics.fmean(b))
    vals.sort()
    return statistics.fmean(xa) / statistics.fmean(xb), vals[int(0.025 * n_boot)], vals[int(0.975 * n_boot) - 1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(HERE.parent / "results"))
    res = Path(ap.parse_args().results)
    items = [r for r in read_rows(res / "items.csv") if r["seed"] == "42"]
    calls = [r for r in read_rows(res / "calls.csv") if r["seed"] == "42"]
    summary = {(s["config"], s["task"]): s for s in summarise_rows(items)}
    speed_run = {(r["config"], r["task"]): r for r in speed_from_calls(res / "calls.csv")}

    L = ["# Results", "",
         "Generated by `analysis/make_report.py` from the raw result files in this folder. "
         "Do not edit by hand.", "",
         "**Definitions.** *Tokens / item* = prompt + completion tokens summed over every model call "
         "of an item (an agent re-sends its whole context at each step). *Reasoning* tokens are part "
         "of completion tokens. Truncated items (token limit reached) count as failures. "
         "*Tokens per correct item* = all tokens of the condition ÷ number of correct items, the "
         "price-independent cost of one *successful* task. "
         f"95% intervals: Wilson for accuracy; percentile bootstrap over items ({N_BOOT:,} resamples, "
         f"seed {BOOT_SEED}) for means; contrasts resample the shared items jointly (paired).", ""]

    # ---------------------------------------------------------------- main tables
    for t in ["T1", "T2", "T4", "T3"]:
        cs = [c for c in ORDER if (c, t) in summary]
        L += [f"## {TASKS[t]}", "",
              "| Model | Setting | Accuracy | 95% CI | Tokens / item | 95% CI | Median | Completion / item "
              "| Reasoning / item | Calls / item | Truncated | Tokens / correct item |",
              "|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
        for c in cs:
            s = summary[(c, t)]
            tok = list(per_item(items, c, t, "total_tokens").values())
            lo, hi = wilson(s["n_correct"], s["n"])
            blo, bhi = boot_mean(tok)
            L.append(f"| {MODEL_OF[c]} | {SETTING_OF[c]} | {pct(s['accuracy'])} | {ci_pct(lo, hi)} | "
                     f"{fmt(s['mean_total_tokens'])} | {ci_int(blo, bhi)} | {fmt(s['median_total_tokens'])} | "
                     f"{fmt(s['mean_completion_tokens'])} | {fmt(s['mean_reasoning_tokens'])} | "
                     f"{fmt(s['mean_calls'], 1)} | {pct(s['truncation_rate'])} | "
                     f"{fmt(s['total_tokens_per_correct_item'])} |")
        L.append("")

    # ---------------------------------------------------------------- contrasts
    L += ["## Paired contrasts: what more reasoning buys", "",
          "Δ accuracy in percentage points and the ratio of mean tokens per item, A relative to B, on "
          "identical items. Intervals: paired bootstrap.", "",
          "| Contrast (A vs B) | Task | Δ accuracy (pp) | 95% CI | Token ratio A/B | 95% CI |",
          "|---|---|--:|--:|--:|--:|"]
    for label, a, b in CONTRASTS + [("Qwen3.8-27B agent: effort low vs thinking off", "Q-A-low", "Q-A")]:
        for t in (["T3"] if CONFIGS[a]["agent"] else ["T1", "T2", "T4"]):
            acc = paired_boot(per_item(items, a, t, "correct"), per_item(items, b, t, "correct"), diff_of_means)
            rat = paired_boot(per_item(items, a, t, "total_tokens"), per_item(items, b, t, "total_tokens"),
                              ratio_of_means)
            L.append(f"| {label} | {t} | {100 * acc[0]:+.0f} | [{100 * acc[1]:+.0f}, {100 * acc[2]:+.0f}] | "
                     f"×{rat[0]:.2f} | [×{rat[1]:.2f}, ×{rat[2]:.2f}] |")
    L.append("")

    # ---------------------------------------------------------------- agent
    qa = list(per_item(items, "Q-A", "T3", "total_tokens").values())
    q2 = list(per_item(items, "Q-off", "T2", "total_tokens").values())
    r, lo, hi = unpaired_ratio_ci(qa, q2)
    L += ["## The agent multiplier", "",
          f"Same weights and setting (Qwen3.8-27B, thinking off): an agentic lookup task (T3) used "
          f"**×{r:.1f}** (95% CI ×{lo:.1f}–×{hi:.1f}, unpaired bootstrap) the tokens of a single-answer "
          f"calculation (T2): {statistics.fmean(qa):,.0f} vs {statistics.fmean(q2):,.0f} tokens per item.", "",
          "| Condition | Calls / item | Tool calls / item | Prompt tokens / item | Completion tokens / item "
          "| Prompt share |", "|---|--:|--:|--:|--:|--:|"]
    for c in ["Q-A", "Q-A-low"]:
        rs = [x for x in items if x["config"] == c and x["task"] == "T3"]
        p = statistics.fmean(int(x["prompt_tokens"]) for x in rs)
        q = statistics.fmean(int(x["completion_tokens"]) for x in rs)
        L.append(f"| {MODEL_OF[c]}, {SETTING_OF[c]} | {statistics.fmean(int(x['n_calls']) for x in rs):.2f} | "
                 f"{statistics.fmean(int(x['n_tool_calls']) for x in rs):.2f} | {p:,.0f} | {q:,.0f} | {p / (p + q):.0%} |")
    L += ["", "Mean prompt tokens per call, by step of the agent loop (the context grows as tool "
          "results are appended):", "", "| Condition | " + " | ".join(f"step {i}" for i in range(5)) + " |",
          "|---|" + "--:|" * 5]
    for c in ["Q-A", "Q-A-low"]:
        by = {}
        for x in calls:
            if x["config"] == c and x["task"] == "T3":
                by.setdefault(int(x["call_index"]), []).append(int(x["prompt_tokens"]))
        L.append(f"| {SETTING_OF[c]} | " + " | ".join(
            f"{statistics.fmean(by[i]):,.0f} (n={len(by[i])})" if i in by else "–" for i in range(5)) + " |")
    L.append("")

    # ---------------------------------------------------------------- failure modes
    notes = {}
    for x in items:
        if x["note"]:
            notes.setdefault((x["config"], x["task"], x["note"]), 0)
            notes[(x["config"], x["task"], x["note"])] += 1
    L += ["## Failure annotations", "",
          "`truncated`: the reply hit the token limit (counted as wrong). `no_answer_line`: no `Answer:` "
          "line; the last number in the reply was scored instead.", "",
          "| Condition | Task | Note | Items |", "|---|---|---|--:|"]
    for (c, t, n), k in sorted(notes.items(), key=lambda kv: (ORDER.index(kv[0][0]), kv[0][1])):
        L.append(f"| {MODEL_OF[c]}, {SETTING_OF[c]} | {t} | `{n}` | {k} |")
    L.append("")

    # ---------------------------------------------------------------- speed
    L += ["## Throughput during the runs", "",
          "Per-request tok/s = completion tokens ÷ request latency (prefill and queueing included). "
          "Aggregate tok/s = all completion tokens of a condition × task ÷ its wall time. Concurrency 8 "
          "(4 for Gemma 4). Short outputs (T1) make per-request rates prefill-bound.", "",
          "| Model | Setting | Task | tok/s per request (median) | aggregate tok/s |", "|---|---|---|--:|--:|"]
    for c in ORDER:
        for t in ["T1", "T2", "T4", "T3"]:
            sp = speed_run.get((c, t))
            if sp:
                L.append(f"| {MODEL_OF[c]} | {SETTING_OF[c]} | {t} | {fmt(sp['per_request_tok_s_median'], 1)} | "
                         f"{fmt(sp['aggregate_tok_s'], 1)} |")
    L += ["", "Single stream (one streamed request at a time, ~400-word answer, 3 runs):", "",
          "| Served model | Condition | Time to first token (s) | Decode tok/s | Output tokens |",
          "|---|---|--:|--:|--:|"]
    for s in read_speed(res / "speed.csv"):
        L.append(f"| `{s['model']}` | {s['config']} | {fmt(s['ttft_s'], 2)} | {fmt(s['decode_tok_s'], 1)} | "
                 f"{fmt(s['completion_tokens'])} |")
    L.append("")

    # ---------------------------------------------------------------- GPU
    g = [x for x in read_rows(res / "gpu.csv") if x["config"]]
    by = {}
    for x in g:
        by.setdefault(MODEL_OF[x["config"]], []).append(x)
    L += ["## GPU utilisation during the runs", "",
          "Sampled every 2 s from the GPU host. Power draw was not available, so no energy figure is reported.", "",
          "| Model | Samples | Mean util % | Max VRAM used (MB) |", "|---|--:|--:|--:|"]
    for m, rs in by.items():
        L.append(f"| {m} | {len(rs)} | {statistics.fmean(float(x['util_pct']) for x in rs):.0f} | "
                 f"{max(float(x['vram_used_mb']) for x in rs):,.0f} |")
    L.append("")

    out = res / "RESULTS.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
